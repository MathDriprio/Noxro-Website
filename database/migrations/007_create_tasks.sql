CREATE TABLE
    tasks (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        vehicle_id BIGINT NULL,
        created_by_user_id BIGINT NOT NULL,
        title VARCHAR(100) NOT NULL,
        description TEXT NULL,
        status VARCHAR(50) NOT NULL DEFAULT 'pending',
        due_date TIMESTAMPTZ NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        updated_at TIMESTAMPTZ NULL,
        deleted_at TIMESTAMPTZ NULL,
        CONSTRAINT pk_tasks PRIMARY KEY (id),
        CONSTRAINT fk_tasks_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE SET NULL,
        CONSTRAINT fk_tasks_created_by_user FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
        CONSTRAINT chk_tasks_status CHECK (
            status IN ('pending', 'in_progress', 'done', 'canceled')
        )
    );
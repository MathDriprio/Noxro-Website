CREATE TABLE
    logs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        user_id BIGINT NOT NULL,
        action VARCHAR(50) NOT NULL,
        entity_type VARCHAR(255) NOT NULL,
        entity_id BIGINT NOT NULL,
        description TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        CONSTRAINT pk_logs PRIMARY KEY (id),
        CONSTRAINT fk_logs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
        CONSTRAINT chk_logs_entity_type CHECK (
            entity_type IN (
                'user',
                'vehicle',
                'maintenance',
                'transaction',
                'task',
                'document',
                'comment'
            )
        ),
        CONSTRAINT chk_logs_action CHECK (char_length(trim(action)) > 0),
        CONSTRAINT chk_logs_description CHECK (char_length(trim(description)) > 0),
        CONSTRAINT chk_logs_entity_id CHECK (action IN ('create', 'update', 'delete'))
    );
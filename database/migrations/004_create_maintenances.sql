CREATE TABLE
    maintenances (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        vehicle_id BIGINT NOT NULL,
        created_by_user_id BIGINT NOT NULL,
        title VARCHAR(100) NOT NULL,
        description TEXT,
        performed_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        updated_at TIMESTAMPTZ NULL,
        deleted_at TIMESTAMPTZ NULL,
        CONSTRAINT pk_maintenances PRIMARY KEY (id),
        CONSTRAINT fk_maintenances_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE CASCADE,
        CONSTRAINT fk_maintenances_user FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
        CONSTRAINT chk_maintenances_title_length CHECK (char_length(trim(title)) >= 3),
        CONSTRAINT chk_maintenances_performed_at CHECK (performed_at <= NOW ())
    );